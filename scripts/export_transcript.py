"""Regenerate `docs/agent-transcript/` from the Claude Code session log.

The submission has to show the prompts the agent was given. Writing that by
hand means it silently falls behind the work, so it is generated:

    python scripts/export_transcript.py

Reads the session JSONL that Claude Code keeps per project, and writes

    docs/agent-transcript/prompts.md       every instruction, verbatim
    docs/agent-transcript/conversation.md  those plus the agent's prose

Email addresses and home directory paths are redacted from both. The session
log lives outside the repo and is not committed; only the rendered Markdown
is.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "agent-transcript"

#: Where Claude Code keeps session logs, one directory per project.
SESSIONS = Path.home() / ".claude" / "projects"

#: Machinery that arrives as a user turn but was not typed by the user.
NOT_A_PROMPT = (
    "<command-name>",
    "<command-message>",
    "<local-command-stdout>",
    "<local-command-stderr>",
)
GENERATED_PREFIXES = (
    "This session is being continued from a previous conversation",
    "Your claude.ai usage limit has reset",
    "Caveat: The messages below were generated by the user while running",
)

EMAIL = re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.]+\b")
#: Any home directory, not just this machine's, in either slash direction.
HOME = re.compile(r"[A-Za-z]:[\\/]Users[\\/][^\\/\s\"']+|/(?:home|Users)/[^/\s\"']+")


def redact(text: str) -> str:
    text = EMAIL.sub("<email redacted>", text)
    return HOME.sub("<home>", text)


def unwrap_pasted(text: str) -> str:
    """Drop the <pasted_content> wrapper, keeping what was pasted.

    The ids are per-session noise the user never sees, and the content is
    part of the instruction.
    """
    return re.sub(
        r"<pasted_content[^>]*>\s*(.*?)\s*</pasted_content>",
        r"\1",
        text,
        flags=re.DOTALL,
    )


def is_prompt(record: dict) -> bool:
    if record.get("type") != "user":
        return False
    if record.get("isMeta") or record.get("isSidechain"):
        return False
    content = record.get("message", {}).get("content")
    if not isinstance(content, str) or not content.strip():
        return False
    stripped = content.lstrip()
    if any(stripped.startswith(tag) for tag in NOT_A_PROMPT):
        return False
    return not any(stripped.startswith(p) for p in GENERATED_PREFIXES)


def assistant_prose(record: dict) -> str:
    """The agent's visible reply, without tool calls or thinking."""
    if record.get("type") != "assistant":
        return ""
    if record.get("isSidechain"):
        return ""
    content = record.get("message", {}).get("content")
    if not isinstance(content, list):
        return ""
    parts = [
        block.get("text", "")
        for block in content
        if isinstance(block, dict) and block.get("type") == "text"
    ]
    return "\n\n".join(p.strip() for p in parts if p.strip())


def read_turns(path: Path) -> list[tuple[str, str]]:
    """(speaker, text) in order, speaker being 'user' or 'assistant'."""
    turns: list[tuple[str, str]] = []
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                continue
            if is_prompt(record):
                text = unwrap_pasted(record["message"]["content"]).strip()
                turns.append(("user", redact(text)))
            else:
                prose = assistant_prose(record)
                if prose:
                    turns.append(("assistant", redact(prose)))
    return turns


def newest_session(project_dir: Path) -> Path:
    """The session with the most prompts: the one the work happened in."""
    best: tuple[int, Path] | None = None
    for candidate in project_dir.glob("*.jsonl"):
        count = 0
        with candidate.open(encoding="utf-8") as handle:
            for line in handle:
                try:
                    if is_prompt(json.loads(line)):
                        count += 1
                except json.JSONDecodeError:
                    continue
        if best is None or count > best[0]:
            best = (count, candidate)
    if best is None:
        sys.exit(f"no session logs in {project_dir}")
    return best[1]


def write_prompts(prompts: list[str]) -> Path:
    lines = [
        "# Prompts given to the coding agent",
        "",
        "Every instruction given to Claude Code during this exercise, in order",
        "and verbatim. Slash commands, tool results and system messages are",
        "omitted. The agent's replies are in `conversation.md`.",
        "",
        f"**{len(prompts)} prompts.** Generated by `scripts/export_transcript.py`.",
        "Email addresses and home directory paths are redacted.",
        "",
        "---",
        "",
    ]
    for number, prompt in enumerate(prompts, 1):
        lines += [f"## Prompt {number}", "", "```text", prompt, "```", ""]
    path = OUT / "prompts.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def write_conversation(turns: list[tuple[str, str]], name: str) -> Path:
    lines = [
        "# Full agent conversation",
        "",
        "The prose of the session: what was asked, and what the agent replied.",
        "Tool calls and their output are omitted, which is what makes this",
        "readable; the reasoning and the findings are all here.",
        "",
        "Generated by `scripts/export_transcript.py`. Email addresses and home",
        "directory paths are redacted.",
        "",
        "---",
        "",
    ]
    for speaker, text in turns:
        lines += [f"## {name if speaker == 'user' else 'Claude'}", "", text, ""]
    path = OUT / "conversation.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--session",
        type=Path,
        help="session JSONL to render (default: the one with the most prompts)",
    )
    parser.add_argument(
        "--name",
        default="Nikolay",
        help="what to call the human in conversation.md",
    )
    args = parser.parse_args()

    session = args.session
    if session is None:
        slug = re.sub(r"[^A-Za-z0-9]", "-", str(ROOT))
        project_dir = SESSIONS / slug
        if not project_dir.is_dir():
            # The slug is derived from the directory Claude Code was started
            # in, which may be a parent of the repo.
            candidates = [d for d in SESSIONS.glob("*") if d.is_dir()]
            project_dir = max(
                candidates,
                key=lambda d: max(
                    (f.stat().st_size for f in d.glob("*.jsonl")), default=0
                ),
                default=None,
            )
            if project_dir is None:
                sys.exit(f"no session logs under {SESSIONS}")
        session = newest_session(project_dir)

    if not session.is_file():
        sys.exit(f"no session log at {session}")

    turns = read_turns(session)
    prompts = [text for speaker, text in turns if speaker == "user"]
    if not prompts:
        sys.exit(f"no prompts found in {session}")

    OUT.mkdir(parents=True, exist_ok=True)
    written = [write_prompts(prompts), write_conversation(turns, args.name)]

    print(f"read {session.name} ({session.stat().st_size // 1024} KB)")
    print(f"  {len(prompts)} prompts, {len(turns) - len(prompts)} agent replies")
    for path in written:
        size = path.stat().st_size // 1024
        print(f"  wrote {path.relative_to(ROOT)} ({size} KB)")

    leaked = [
        p.name
        for p in written
        if EMAIL.search(p.read_text(encoding="utf-8"))
        or re.search(r"[A-Za-z]:[\\/]Users[\\/]", p.read_text(encoding="utf-8"))
    ]
    if leaked:
        sys.exit(f"redaction failed in {', '.join(leaked)}")
    print("  redaction checked: no email addresses or home paths")
    return 0


if __name__ == "__main__":
    os.environ.setdefault("PYTHONIOENCODING", "utf-8")
    raise SystemExit(main())
